# ---------------- FIVE BUILT-IN FUNCTIONS ----------------

def show(*values, sep=" ", end="\n"):
    """Display output."""
    print(*values, sep=sep, end=end)


def ask(prompt=""):
    """Accept user input."""
    return input(prompt)


def pause(seconds):
    """Pause program execution."""
    time.sleep(float(seconds))


def roll(minimum=1, maximum=100):
    """Generate a random integer."""
    minimum = int(minimum)
    maximum = int(maximum)

    if minimum > maximum:
        raise ValueError("Minimum cannot exceed maximum.")

    return random.randint(minimum, maximum)


def inside(value, low, high):
    """Check whether a value is inside an inclusive range."""
    return low <= value <= high


# ---------------- NEXLANG TRANSLATOR ----------------

def translate(source):

    output = [
        "# Generated by NexLang 2.1",
        "import time",
        "import random"
    ]

    block_stack = []
    last_when = {}
    pending_indent = None

    for line_number, original in enumerate(source.splitlines(), 1):

        stripped = original.strip()

        if not stripped:
            output.append("")
            continue

        indent_text = original[:len(original) - len(original.lstrip())]

        if "\t" in indent_text:
            raise SyntaxError(
                f"Line {line_number}: Tabs are not allowed. Use 4 spaces."
            )

        indent = len(indent_text)

        if indent % 4 != 0:
            raise SyntaxError(
                f"Line {line_number}: Use multiples of 4 spaces."
            )

        # Preserve comments
        if stripped.startswith("#"):
            output.append(original)
            continue

        # Validate indentation
        if pending_indent is not None:

            if indent != pending_indent:
                raise SyntaxError(
                    f"Line {line_number}: Invalid indentation. "
                    f"Expected {pending_indent} spaces."
                )

            pending_indent = None

        else:

            while block_stack and indent <= block_stack[-1][0]:
                block_stack.pop()

            expected = (
                block_stack[-1][0] + 4
                if block_stack else 0
            )

            if indent != expected:
                raise SyntaxError(
                    f"Line {line_number}: Invalid indentation. "
                    f"Expected {expected} spaces."
                )

        prefix = " " * indent
        translated = stripped
        opens_block = False
        block_type = "normal"

        # KEYWORD 1: repeat
        if stripped.startswith("repeat ") and stripped.endswith(":"):

            count = stripped[7:-1].strip()

            if not count:
                raise SyntaxError(
                    f"Line {line_number}: Missing repeat count."
                )

            translated = f"for _nexlang_i in range({count}):"

            opens_block = True
            block_type = "repeat"
            last_when[indent] = False

        # KEYWORD 2: when
        elif stripped.startswith("when ") and stripped.endswith(":"):

            condition = stripped[5:-1].strip()

            if not condition:
                raise SyntaxError(
                    f"Line {line_number}: Missing condition."
                )

            translated = f"if {condition}:"
            opens_block = True
            block_type = "when"
            last_when[indent] = True

        # KEYWORD 3: otherwise
        elif stripped == "otherwise:":

            if not last_when.get(indent, False):
                raise SyntaxError(
                    f"Line {line_number}: 'otherwise' must follow "
                    f"a matching 'when' block."
                )

            translated = "else:"
            opens_block = True
            block_type = "otherwise"
            last_when[indent] = False

        # KEYWORD 4: unless
        elif stripped.startswith("unless ") and stripped.endswith(":"):

            condition = stripped[7:-1].strip()

            if not condition:
                raise SyntaxError(
                    f"Line {line_number}: Missing condition."
                )

            translated = f"if not ({condition}):"
            opens_block = True
            block_type = "unless"
            last_when[indent] = False

        # KEYWORD 5: forever
        elif stripped == "forever:":

            translated = "while True:"
            opens_block = True
            block_type = "forever"
            last_when[indent] = False

        else:
            # Allow normal Python statements and expressions
            # inside NexLang programs.
            translated = stripped
            last_when[indent] = False

        # Clear conditional history from deeper indentation levels
        for level in list(last_when):
            if level > indent:
                del last_when[level]

        output.append(prefix + translated)

        if opens_block:
            block_stack.append((indent, block_type))
            pending_indent = indent + 4

    if pending_indent is not None:
        raise SyntaxError("A block is missing its body.")

    python_source = "\n".join(output)

    # Validate using the CPython compiler
    try:
        compile(python_source, "<NexLang>", "exec")
    except SyntaxError as error:
        raise SyntaxError(
            f"Generated Python syntax error: {error.msg}"
        ) from error

    return python_source


# ---------------- NEXLANG EXECUTION ENGINE ----------------

def run_file(filename):

    path = Path(filename)

    if not path.is_file():
        print(f"File not found: {filename}")
        return 1

    try:
        source = path.read_text(encoding="utf-8")

        python_code = translate(source)

        environment = {
            "__name__": "__main__",
            "show": show,
            "ask": ask,
            "pause": pause,
            "roll": roll,
            "inside": inside,
        }

        compiled_code = compile(
            python_code,
            str(path),
            "exec"
        )

        exec(compiled_code, environment)

        return 0

    except Exception as error:
        print(f"NexLang Error: {error}")
        return 1


# ---------------- COMMAND LINE INTERFACE ----------------

def main():

    if len(sys.argv) != 2:
        print("NexLang 2.1")
        print("Usage: python nexlang.py <file.nx>")
        return 1

    return run_file(sys.argv[1])


if __name__ == "__main__":
    sys.exit(main())
